"""Tests for VsSource._find_script: matching .vs includes to generator scripts."""

import os
import sys
import textwrap
from pathlib import Path

from VeriSnip.vs_build import VsBuilder


def test_exact_vs_name_matches_same_named_script(tmp_path: Path):
    """`include \"widget.vs\"` must resolve to widget.py with an empty suffix."""
    script = tmp_path / "widget.py"
    script.write_text("#!/usr/bin/env python3\n", encoding="utf-8")
    source = VsBuilder.VsSource("widget.vs")

    found, suffix = source._find_script([str(script)])

    assert found == str(script)
    assert suffix == ""


def test_prefixed_vs_matches_script_stem_without_vs_in_suffix(tmp_path: Path):
    """`include \"widget_logic.vs\"` matching widget.py passes suffix \"logic\"."""
    script = tmp_path / "widget.py"
    script.write_text("#!/usr/bin/env python3\n", encoding="utf-8")
    source = VsBuilder.VsSource("widget_logic.vs")

    found, suffix = source._find_script([str(script)])

    assert found == str(script)
    assert suffix == "logic"


